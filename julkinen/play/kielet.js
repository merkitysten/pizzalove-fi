let KIELI = 'fi';

/* KIELEN VALINTA SIVULTA TULLESSA (pizzalove.fi, 6.10.2026)
 * 1. ?kieli=xx osoitteessa voittaa: pizzalove.fi:n kielivalinta kulkee peliin.
 *    Valinta kirjoitetaan myös tallennettuihin asetuksiin, jotta peli.js ja
 *    isanta.js lukevat sen omassa lataaAsetukset-vaiheessaan.
 * 2. Jos kieltä ei ole koskaan valittu, käytetään selaimen kieltä. Tämä koskee
 *    erityisesti QR-koodilla liittyvää pelaajaa: hänen linkissään ei ole ?kieli=.
 * ⚠️ Avain 'pizzapeli-asetukset' on sama kuin peli.js:n ASETUSAVAIN. */
/* ⚠️ TALLENNETTU KIELI EI PÄÄDY TÄHÄN `KIELI`-MUUTTUJAAN, JA SE ON TARKOITUS
 * (mitattu 14.10.2026): korttipelissä `peli.js` ja `isanta.js` lukevat sen
 * omassa `lataaAsetukset`-vaiheessaan. Osoitteessa tullut kieli kirjoitetaan
 * tässä, tallennettua ei lueta takaisin.
 *
 * Lautapelillä ei ole sitä vaihetta — se on yksi komponentti, joka lukee
 * kielen kerran käynnistyessään. Siksi lukija on oma funktionsa eikä
 * apinavaaan omaa `localStorage`-kutsua: avain saa olla vain yhdessä
 * paikassa, ja «onko kieli valmis» on sama kysymys molemmille. */
const KIELI_ASETUSAVAIN = 'pizzapeli-asetukset';

function tallennettuKieli() {
  try {
    var a = JSON.parse(localStorage.getItem(KIELI_ASETUSAVAIN) || 'null') || {};
    return (a.kieli && KIELET[a.kieli] && KIELET[a.kieli].valmis) ? a.kieli : '';
  } catch (e) { return ''; /* yksityinen selaus */ }
}

(function () {
  try {
    var AVAIN = KIELI_ASETUSAVAIN;
    var a = JSON.parse(localStorage.getItem(AVAIN) || 'null') || {};
    var k = new URLSearchParams(location.search).get('kieli');
    if (!(k && KIELET[k] && KIELET[k].valmis) && !a.kieli) {
      var selain = navigator.languages || [navigator.language || ''];
      for (var i = 0; i < selain.length; i++) {
        var s = String(selain[i]).slice(0, 2).toLowerCase();
        if (KIELET[s] && KIELET[s].valmis) { k = s; break; }
      }
      if (!k) k = 'en';
    }
    if (k && KIELET[k] && KIELET[k].valmis) {
      KIELI = k;
      a.kieli = k;
      localStorage.setItem(AVAIN, JSON.stringify(a));
    }
  } catch (e) { /* yksityinen selaus: oletuskieli */ }
  /* Välilehden otsikko valitulla kielellä (index.html:n <title> on suomeksi). */
  var OTSIKKO = { sv: 'Pizza Party — så spelar man', en: 'Pizza Party — how to play',
                  de: 'Pizza Party — so wird gespielt' };
  if (OTSIKKO[KIELI] && /näin sitä pelataan/.test(document.title)) document.title = OTSIKKO[KIELI];
})();

/* ⚠️ PUUTTUVA AVAIN PALAUTTAA AVAIMEN, EI TYHJÄÄ. Tyhjä merkkijono näyttää
 * ruudulla samalta kuin «tähän ei kuulu tekstiä», ja silloin puuttuva käännös
 * on näkymätön. Avain ruudulla on ruma — ja siksi se korjataan. */
function t(avain, arvot) {
  const kieli = KIELET[KIELI] || KIELET.fi;
  let s = kieli.t[avain];
  if (s === undefined) s = KIELET.fi.t[avain];
  if (s === undefined) return avain;
  if (arvot) {
    Object.keys(arvot).forEach(function (k) {
      s = s.split('{' + k + '}').join(arvot[k]);
    });
  }
  return s;
}

function kielenNimi(avain) { return (KIELET[avain] || {}).nimi || avain; }

function valmiitKielet() {
  return Object.keys(KIELET).filter(function (k) { return KIELET[k].valmis; });
}

/* Kääntää kaiken minkä merkintä osoittaa. Ajetaan latauksessa ja kielen
 * vaihdossa — ei muualla, jotta käännös on yhdessä paikassa eikä siroteltuna. */
function kaannaSivu(juuri) {
  const j = juuri || document;
  [].forEach.call(j.querySelectorAll('[data-t]'), function (n) {
    n.textContent = t(n.dataset.t);
  });
  [].forEach.call(j.querySelectorAll('[data-th]'), function (n) {
    n.innerHTML = t(n.dataset.th);
  });
  [].forEach.call(j.querySelectorAll('[data-ta]'), function (n) {
    n.setAttribute('aria-label', t(n.dataset.ta));
  });
  /* ⚠️ alt on OMA merkintansa eika aria-labelin muunnelma. Mutaatiokoe
   * 9.9.2026 nayttoi etta pelipalkin kahdeksan `aria-label`/`alt`-tekstia
   * jaivat kaantymatta: koneisto katti vain nakyvan tekstin. Ruudunlukijan
   * teksti on kayttoliittymatekstia siina missa muukin. */
  [].forEach.call(j.querySelectorAll('[data-talt]'), function (n) {
    n.setAttribute('alt', t(n.dataset.talt));
  });
  /* Kenttien paikkamerkkiteksti on käyttöliittymätekstiä siinä missä muukin. */
  [].forEach.call(j.querySelectorAll('[data-tp]'), function (n) {
    n.setAttribute('placeholder', t(n.dataset.tp));
  });
  document.documentElement.lang = KIELI;
}
